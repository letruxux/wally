export function getFileIconUrl(filename: string): string {
  const lower = filename.toLowerCase();

  const exact = FILE_NAMES[lower];
  if (exact) return `${ICONS_BASE}/${exact}.svg`;

  const parts = lower.split(".");
  if (parts.length > 1) {
    for (let i = parts.length - 1; i >= 1; i--) {
      const ext = parts.slice(i).join(".");
      const icon = FILE_EXTENSIONS[ext];
      if (icon) return `${ICONS_BASE}/${icon}.svg`;
    }
  }

  return `${ICONS_BASE}/_file.svg`;
}

export function getFolderIconUrl(name: string, expanded: boolean): string {
  const lower = name.toLowerCase();
  const iconId = FOLDER_NAMES[lower];
  if (iconId) {
    return `${ICONS_BASE}/folder_${iconId}${expanded ? "_open" : ""}.svg`;
  }
  return `${ICONS_BASE}/${expanded ? "_folder_open" : "_folder"}.svg`;
}
